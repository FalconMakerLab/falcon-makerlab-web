import { readdir, readFile, mkdir, writeFile, cp } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve('content/projects');
const escape = (value) =>
  value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
// Intentionally small Markdown subset: headings, paragraphs, unordered lists and fenced code.
// Raw HTML is escaped; no remote content or runtime Markdown requests are required.
export function markdown(source) {
  let html = '',
    paragraph = [],
    list = false,
    code = false,
    codeLines = [];
  const flush = () => {
    if (paragraph.length) {
      html += `<p>${escape(paragraph.join(' '))}</p>`;
      paragraph = [];
    }
  };
  for (const line of source.split(/\r?\n/)) {
    if (line.startsWith('```')) {
      flush();
      if (list) {
        html += '</ul>';
        list = false;
      }
      if (code) {
        html += `<pre><code>${escape(codeLines.join('\n'))}</code></pre>`;
        codeLines = [];
      }
      code = !code;
      continue;
    }
    if (code) {
      codeLines.push(line);
      continue;
    }
    if (!line.startsWith('- ') && list) {
      html += '</ul>';
      list = false;
    }
    const heading = /^(#{1,3}) (.+)$/.exec(line);
    if (heading) {
      flush();
      const level = Math.max(2, heading[1].length);
      html += `<h${level}>${escape(heading[2])}</h${level}>`;
    } else if (line.startsWith('- ')) {
      flush();
      if (!list) {
        html += '<ul>';
        list = true;
      }
      html += `<li>${escape(line.slice(2))}</li>`;
    } else if (!line.trim()) flush();
    else paragraph.push(line.trim());
  }
  if (code) throw new Error('Unclosed Markdown code fence');
  flush();
  if (list) html += '</ul>';
  return html;
}
const projects = [];
for (const entry of await readdir(root, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const directory = resolve(root, entry.name);
  const metadata = JSON.parse(await readFile(resolve(directory, 'project.json'), 'utf8'));
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(metadata.slug) || metadata.slug !== entry.name)
    throw new Error(`Invalid slug: ${entry.name}`);
  if (
    !metadata.categories?.length ||
    metadata.categories.some((c) => !['code', 'make', 'grow'].includes(c))
  )
    throw new Error(`Invalid categories: ${entry.name}`);
  if (!metadata.image?.startsWith('/projects/')) throw new Error(`Invalid image: ${entry.name}`);
  for (const locale of ['pl', 'en']) {
    if (!metadata[locale]?.title || !metadata[locale]?.summary)
      throw new Error(`Missing ${locale} metadata: ${entry.name}`);
    const body = await readFile(resolve(directory, `${locale}.md`), 'utf8');
    projects.push({
      slug: metadata.slug,
      categories: metadata.categories,
      featured: !!metadata.featured,
      image: metadata.image,
      status: metadata.status,
      ...metadata[locale],
      locale,
      html: markdown(body),
    });
  }
  await mkdir(resolve('public/projects', entry.name), { recursive: true });
  await cp(resolve(directory, 'assets'), resolve('public/projects', entry.name), {
    recursive: true,
  });
}
for (const locale of ['pl', 'en'])
  if (projects.filter((p) => p.locale === locale && p.featured).length !== 1)
    throw new Error(`Exactly one featured project required for ${locale}`);
await mkdir('src/app/generated', { recursive: true });
await writeFile(
  'src/app/generated/projects.ts',
  `// Generated by scripts/content.mjs. Edit content/projects instead.\nimport { LocalizedProject } from '../content';\nexport const projects: LocalizedProject[] = ${JSON.stringify(projects, null, 2)};\n`,
);
const paths = [
  '',
  ...['pl', 'en'].flatMap((locale) => [
    locale,
    `${locale}/projects`,
    `${locale}/about`,
    `${locale}/contact`,
    ...projects.filter((p) => p.locale === locale).map((p) => `${locale}/projects/${p.slug}`),
  ]),
];
await writeFile(
  'public/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${paths.map((p) => `<url><loc>https://falcon-codes.pl/${p}</loc></url>`).join('')}</urlset>`,
);
console.log(`Content ready: ${projects.length} localized projects, ${paths.length} URLs.`);
